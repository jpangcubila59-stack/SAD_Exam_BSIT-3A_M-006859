CREATE OR REPLACE FUNCTION public.is_scholarship_staff()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.profiles
        WHERE id = (SELECT auth.uid())
          AND role::TEXT IN ('staff', 'admin')
    );
$$;

CREATE OR REPLACE FUNCTION public.owns_scholar_assignment(target_id BIGINT)
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.assignments
        WHERE id = target_id AND scholar_id = (SELECT auth.uid())
    );
$$;

REVOKE ALL ON FUNCTION public.is_scholarship_staff() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.owns_scholar_assignment(BIGINT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_scholarship_staff() TO authenticated;
GRANT EXECUTE ON FUNCTION public.owns_scholar_assignment(BIGINT) TO authenticated;

CREATE OR REPLACE FUNCTION public.guard_scholarship_assignment()
RETURNS TRIGGER
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF NOT public.is_scholarship_staff() THEN
        IF TG_OP = 'INSERT' THEN
            IF NEW.scholar_id IS DISTINCT FROM (SELECT auth.uid()) THEN
                RAISE EXCEPTION 'You may select a program only for your own scholar account.';
            END IF;
            PERFORM 1 FROM public.profiles
            WHERE id = NEW.scholar_id
            FOR UPDATE;
            IF EXISTS (
                SELECT 1 FROM public.assignments
                WHERE scholar_id = NEW.scholar_id
            ) THEN
                RAISE EXCEPTION 'A scholar may have only one program assignment.';
            END IF;
        ELSE
            IF OLD.scholar_id IS DISTINCT FROM (SELECT auth.uid())
              OR NEW.scholar_id IS DISTINCT FROM OLD.scholar_id
              OR NEW.assigned_by IS DISTINCT FROM OLD.assigned_by
              OR NEW.assigned_at IS DISTINCT FROM OLD.assigned_at
              OR NEW.notes IS DISTINCT FROM OLD.notes
              OR NEW.award_status IS DISTINCT FROM OLD.award_status THEN
                RAISE EXCEPTION 'You may only change your own scholarship program.';
            END IF;
            IF NEW.program_id IS NOT DISTINCT FROM OLD.program_id THEN
                RAISE EXCEPTION 'Select a different scholarship program.';
            END IF;
            IF EXISTS (
                SELECT 1 FROM public.submissions
                WHERE assignment_id = OLD.id
            ) THEN
                RAISE EXCEPTION 'A scholarship program cannot be changed after the first submission.';
            END IF;
        END IF;

        IF NOT EXISTS (
            SELECT 1 FROM public.programs
            WHERE id = NEW.program_id AND is_active
        ) THEN
            RAISE EXCEPTION 'Select an active scholarship program.';
        END IF;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM public.profiles
        WHERE id = NEW.scholar_id AND role::TEXT = 'scholar'
    ) THEN
        RAISE EXCEPTION 'Only scholar profiles can receive scholarship assignments.';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.guard_scholarship_submission()
RETURNS TRIGGER
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    policy_row public.programs%ROWTYPE;
    reasons TEXT[] := ARRAY[]::TEXT[];
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NOT public.owns_scholar_assignment(NEW.assignment_id) THEN
            RAISE EXCEPTION 'You may submit only for your assigned scholarship.';
        END IF;
        RETURN NEW;
    END IF;

    IF public.is_scholarship_staff() THEN
        IF NEW.assignment_id IS DISTINCT FROM OLD.assignment_id
          OR NEW.academic_year IS DISTINCT FROM OLD.academic_year
          OR NEW.semester IS DISTINCT FROM OLD.semester
          OR NEW.gwa IS DISTINCT FROM OLD.gwa
          OR NEW.units_completed IS DISTINCT FROM OLD.units_completed
          OR NEW.failed_subjects IS DISTINCT FROM OLD.failed_subjects
          OR NEW.incomplete_subjects IS DISTINCT FROM OLD.incomplete_subjects
          OR NEW.dropped_subjects IS DISTINCT FROM OLD.dropped_subjects
          OR NEW.evidence_reference IS DISTINCT FROM OLD.evidence_reference
          OR NEW.submitted_at IS DISTINCT FROM OLD.submitted_at THEN
            RAISE EXCEPTION 'Staff may not alter scholar-submitted academic data.';
        END IF;

        IF NEW.verification_status IS DISTINCT FROM OLD.verification_status THEN
            IF NEW.verification_status NOT IN ('verified', 'returned') THEN
                RAISE EXCEPTION 'Verification must be marked verified or returned.';
            END IF;
            IF NEW.verification_status = 'returned'
              AND COALESCE(length(trim(NEW.verification_reason)), 0) = 0 THEN
                RAISE EXCEPTION 'Enter a reason before returning evidence.';
            END IF;
            NEW.compliance_status := 'pending';
            NEW.compliance_reasons := '[]'::JSONB;
            NEW.deficiency_reasons := '';
            NEW.evaluated_at := NULL;
            NEW.evaluated_by := NULL;
            NEW.renewal_status := 'pending';
            NEW.renewal_note := NULL;
            NEW.decided_by := NULL;
            NEW.decided_at := NULL;
            RETURN NEW;
        ELSIF NEW.verification_reason IS DISTINCT FROM OLD.verification_reason THEN
            RAISE EXCEPTION 'Verification feedback can only change with verification status.';
        END IF;

        IF NEW.compliance_status IS DISTINCT FROM OLD.compliance_status THEN
            IF OLD.verification_status <> 'verified'
              OR OLD.compliance_status <> 'pending'
              OR NEW.compliance_status NOT IN ('compliant', 'with_deficiency') THEN
                RAISE EXCEPTION 'Only verified, unevaluated submissions can be evaluated.';
            END IF;

            SELECT p.* INTO policy_row
            FROM public.assignments a
            JOIN public.programs p ON p.id = a.program_id
            WHERE a.id = OLD.assignment_id;
            IF NOT FOUND THEN
                RAISE EXCEPTION 'Scholarship program was not found.';
            END IF;

            IF OLD.gwa IS NULL OR OLD.gwa > policy_row.max_gwa THEN
                reasons := array_append(reasons, format('GWA %s exceeds the program limit of %s.', COALESCE(OLD.gwa::TEXT, 'missing'), policy_row.max_gwa));
            END IF;
            IF OLD.units_completed < policy_row.min_units THEN
                reasons := array_append(reasons, format('Completed units %s are below the minimum of %s.', OLD.units_completed, policy_row.min_units));
            END IF;
            IF OLD.failed_subjects > policy_row.max_failed THEN
                reasons := array_append(reasons, format('Failed subjects %s exceed the allowed maximum of %s.', OLD.failed_subjects, policy_row.max_failed));
            END IF;
            IF OLD.incomplete_subjects > policy_row.max_incomplete THEN
                reasons := array_append(reasons, format('Incomplete grades %s exceed the allowed maximum of %s.', OLD.incomplete_subjects, policy_row.max_incomplete));
            END IF;
            IF OLD.dropped_subjects > policy_row.max_dropped THEN
                reasons := array_append(reasons, format('Dropped subjects %s exceed the allowed maximum of %s.', OLD.dropped_subjects, policy_row.max_dropped));
            END IF;
            IF policy_row.deadline IS NOT NULL AND OLD.submitted_at > policy_row.deadline THEN
                reasons := array_append(reasons, 'Submission was received after the program deadline.');
            END IF;

            NEW.compliance_status := CASE WHEN cardinality(reasons) = 0 THEN 'compliant' ELSE 'with_deficiency' END;
            NEW.compliance_reasons := to_jsonb(reasons);
            NEW.deficiency_reasons := array_to_string(reasons, '; ');
            NEW.evaluated_at := now();
            NEW.evaluated_by := (SELECT auth.uid());
            NEW.renewal_status := 'pending';
            NEW.renewal_note := NULL;
            NEW.decided_by := NULL;
            NEW.decided_at := NULL;
            RETURN NEW;
        END IF;

        IF NEW.renewal_status IS DISTINCT FROM OLD.renewal_status THEN
            IF OLD.verification_status <> 'verified'
              OR OLD.compliance_status = 'pending'
              OR NEW.renewal_status NOT IN ('approved', 'held') THEN
                RAISE EXCEPTION 'Evaluate a verified submission before recording a renewal decision.';
            END IF;
            IF NEW.renewal_status = 'approved' AND OLD.compliance_status <> 'compliant' THEN
                RAISE EXCEPTION 'Renewal approval requires a compliant evaluation.';
            END IF;
            IF COALESCE(length(trim(NEW.renewal_note)), 0) = 0 THEN
                RAISE EXCEPTION 'Enter a note for the renewal decision.';
            END IF;
            NEW.decided_by := (SELECT auth.uid());
            NEW.decided_at := now();
            NEW.notes := NEW.renewal_note;
            RETURN NEW;
        END IF;

        RAISE EXCEPTION 'No supported staff workflow change was supplied.';
    END IF;

    IF NOT public.owns_scholar_assignment(OLD.assignment_id)
      OR OLD.verification_status <> 'returned'
      OR NEW.assignment_id IS DISTINCT FROM OLD.assignment_id
      OR NEW.academic_year IS DISTINCT FROM OLD.academic_year
      OR NEW.semester IS DISTINCT FROM OLD.semester
      OR NEW.submitted_at IS DISTINCT FROM OLD.submitted_at THEN
        RAISE EXCEPTION 'Only returned submissions may be corrected, and their semester cannot be changed.';
    END IF;

    NEW.verification_status := 'pending';
    NEW.verification_reason := NULL;
    NEW.compliance_status := 'pending';
    NEW.compliance_reasons := '[]'::JSONB;
    NEW.deficiency_reasons := '';
    NEW.evaluated_at := NULL;
    NEW.evaluated_by := NULL;
    NEW.renewal_status := 'pending';
    NEW.renewal_note := NULL;
    NEW.decided_by := NULL;
    NEW.decided_at := NULL;
    NEW.submitted_at := now();
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.log_scholarship_submission_history()
RETURNS TRIGGER
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    event_name TEXT;
    event_details JSONB := '{}'::JSONB;
BEGIN
    IF TG_OP = 'INSERT' THEN
        event_name := 'submitted';
        event_details := jsonb_build_object('academic_year', NEW.academic_year, 'semester', NEW.semester);
    ELSIF NEW.verification_status IS DISTINCT FROM OLD.verification_status THEN
        event_name := CASE NEW.verification_status WHEN 'verified' THEN 'verified' ELSE 'returned' END;
        event_details := jsonb_build_object('reason', NEW.verification_reason);
    ELSIF NEW.compliance_status IS DISTINCT FROM OLD.compliance_status THEN
        event_name := 'evaluated';
        event_details := jsonb_build_object('status', NEW.compliance_status, 'reasons', NEW.compliance_reasons);
    ELSIF NEW.renewal_status IS DISTINCT FROM OLD.renewal_status THEN
        event_name := 'renewal_decided';
        event_details := jsonb_build_object('status', NEW.renewal_status, 'note', NEW.renewal_note);
    ELSIF OLD.verification_status = 'returned' THEN
        event_name := 'corrected_and_resubmitted';
    ELSE
        RETURN NEW;
    END IF;

    INSERT INTO public.submission_history (submission_id, changed_by, action, details)
    VALUES (NEW.id, (SELECT auth.uid()), event_name, event_details);
    RETURN NEW;
END;
$$;

