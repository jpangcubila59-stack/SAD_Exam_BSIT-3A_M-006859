    ADD COLUMN IF NOT EXISTS student_id TEXT,
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

CREATE UNIQUE INDEX IF NOT EXISTS profiles_student_id_key
    ON public.profiles(student_id)
    WHERE student_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.programs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT DEFAULT '',
    max_gwa NUMERIC(4,2) NOT NULL CHECK (max_gwa > 0),
    min_units INTEGER NOT NULL DEFAULT 0 CHECK (min_units >= 0),
    max_failed INTEGER NOT NULL DEFAULT 0 CHECK (max_failed >= 0),
    max_incomplete INTEGER NOT NULL DEFAULT 0 CHECK (max_incomplete >= 0),
    max_dropped INTEGER NOT NULL DEFAULT 0 CHECK (max_dropped >= 0),
    deadline TIMESTAMPTZ,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scholar_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    program_id BIGINT NOT NULL REFERENCES public.programs(id),
    assigned_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    notes TEXT DEFAULT '',
    UNIQUE (scholar_id, program_id)
);

CREATE TABLE IF NOT EXISTS public.submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES public.assignments(id) ON DELETE CASCADE,
    academic_year TEXT NOT NULL,
    semester TEXT NOT NULL,
    gwa NUMERIC(4,2),
    units_completed INTEGER NOT NULL DEFAULT 0 CHECK (units_completed >= 0),
    failed_subjects INTEGER NOT NULL DEFAULT 0 CHECK (failed_subjects >= 0),
    incomplete_subjects INTEGER NOT NULL DEFAULT 0 CHECK (incomplete_subjects >= 0),
    dropped_subjects INTEGER NOT NULL DEFAULT 0 CHECK (dropped_subjects >= 0),
    evidence_reference TEXT DEFAULT '',
    verification_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (verification_status IN ('pending', 'verified', 'returned')),
    compliance_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (compliance_status IN ('pending', 'compliant', 'with_deficiency')),
    deficiency_reasons TEXT DEFAULT '',
    evaluated_at TIMESTAMPTZ,
    evaluated_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    renewal_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (renewal_status IN ('pending', 'approved', 'held')),
    notes TEXT DEFAULT '',
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (assignment_id, academic_year, semester)
);

CREATE TABLE IF NOT EXISTS public.submission_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT REFERENCES public.submissions(id) ON DELETE SET NULL,
    changed_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

